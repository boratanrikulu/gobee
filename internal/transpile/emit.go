func (e *emitter) formatCall(call *ast.CallExpr) (string, error) {
	// Type conversion: T(x) where T is a Go basic type → (C-T)(x).
	if id, ok := call.Fun.(*ast.Ident); ok {
		if cType, isType := goBasicNameToC[id.Name]; isType {
			if len(call.Args) != 1 {
				return "", fmt.Errorf("%s: type conversion expects exactly one argument", e.prog.FileSet.Position(call.Pos()))
			}
			inner, err := e.formatExpr(call.Args[0])
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("(%s)(%s)", cType, inner), nil
		}
	}

	// unsafe.Pointer(x) → x. C uses void* implicitly, so the cast is a no-op.
	if sel, ok := call.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Pointer" {
		if pkg, ok := sel.X.(*ast.Ident); ok && pkg.Name == "unsafe" {
			if len(call.Args) != 1 {
				return "", fmt.Errorf("%s: unsafe.Pointer expects exactly one argument", e.prog.FileSet.Position(call.Pos()))
			}
			return e.formatExpr(call.Args[0])
		}
	}

	// Ringbuf Submit / Discard / Output (Reserve is handled in writeAssignStmt's
	// comma-ok path).
	if c, ok, err := e.ringbufMethodCall(call); err != nil {
		return "", err
	} else if ok {
		return c, nil
	}

	// Queue / Stack: Push, Pop, Peek.
	if c, ok, err := e.queueLikeMethodCall(call); err != nil {
		return "", err
	} else if ok {
		return c, nil
	}

	// ProgArray.TailCall(ctx, key).
	if c, ok, err := e.progArrayMethodCall(call); err != nil {
		return "", err
	} else if ok {
		return c, nil
	}

	// PerfEventArray.Output(ctx, value).
	if c, ok, err := e.perfEventArrayMethodCall(call); err != nil {
		return "", err
	} else if ok {
		return c, nil
	}

	// TaskStorage / SkStorage / InodeStorage: Get, GetOrCreate, Delete.
	if c, ok, err := e.storageMethodCall(call); err != nil {
		return "", err
	} else if ok {
		return c, nil
	}

	// DevMap / CpuMap / XskMap: Redirect(ctx, key, flags). All three
	// share `bpf_redirect_map` and return XDP_REDIRECT or XDP_ABORTED.
	if c, ok, err := e.redirectMapCall(call); err != nil {
		return "", err
	} else if ok {
		return c, nil
	}

	// Map method calls: PktCount.Update(&k, &v), etc.
	if mapName, _, helper, isMap := e.mapMethodCall(call); isMap {
		args := []string{"&" + mapName}
		for _, a := range call.Args {
			s, err := e.formatExpr(a)
			if err != nil {
				return "", err
			}
			args = append(args, s)
		}
		if helper == "bpf_map_update_elem" {
			args = append(args, "BPF_ANY")
		}
		return fmt.Sprintf("%s(%s)", helper, strings.Join(args, ", ")), nil
	}

	// bpf.HelperFunc(args). Three resolution paths, in order:
	//   1. Sugar expansions: bpf.GetCurrentPid() etc. expand to specific
	//      C expressions instead of a one-to-one helper-name swap.
	//   2. Hand overrides: bpf.AtomicAdd64 → __sync_fetch_and_add.
	//   3. Auto-translation: bpf.MapLookupElem → bpf_map_lookup_elem.
	if sel, ok := call.Fun.(*ast.SelectorExpr); ok {
		if pkgIdent, ok := sel.X.(*ast.Ident); ok {
			if obj := e.prog.Info.Uses[pkgIdent]; obj != nil {
				if pkgName, ok := obj.(*types.PkgName); ok && pkgName.Imported().Path() == bpfPkgPath {
					argStrs := make([]string, len(call.Args))
					for i, a := range call.Args {
						s, err := e.formatExpr(a)
						if err != nil {
							return "", err
						}
						argStrs[i] = s
					}
					if expand, ok := bpfHelperExpansions[sel.Sel.Name]; ok {
						return expand(argStrs)
					}
					cName, known := bpfHelperFuncs[sel.Sel.Name]
					if !known {
						cName = goNameToBpfHelper(sel.Sel.Name)
					}
					return fmt.Sprintf("%s(%s)", cName, strings.Join(argStrs, ", ")), nil
				}
			}
		}
	}

	// Fall-through: user function call.
	fn, err := e.formatExpr(call.Fun)
	if err != nil {
		return "", err
	}
	argStrs := make([]string, len(call.Args))
	for i, a := range call.Args {
		s, err := e.formatExpr(a)
		if err != nil {
			return "", err
		}
		argStrs[i] = s
	}
	return fmt.Sprintf("%s(%s)", fn, strings.Join(argStrs, ", ")), nil
}

// redirectMapCall handles Redirect(ctx, key, flags) on a DevMap, CpuMap,
// or XskMap. All three route to the single bpf_redirect_map helper; the
// userspace-controlled slot contents (ifindex / cpu / xsk fd) determine
// where the packet actually lands.
func (e *emitter) redirectMapCall(call *ast.CallExpr) (string, bool, error) {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return "", false, nil
	}
	if sel.Sel.Name != "Redirect" {
		return "", false, nil
	}
	id, ok := sel.X.(*ast.Ident)
	if !ok {
		return "", false, nil
	}
	t := e.prog.Info.TypeOf(sel.X)
	if t == nil {
		return "", false, nil
	}
	if ptr, isPtr := t.(*types.Pointer); isPtr {
		t = ptr.Elem()
	}
	named, ok := t.(*types.Named)
	if !ok {
		return "", false, nil
	}
	obj := named.Obj()
	if obj.Pkg() == nil || obj.Pkg().Path() != bpfPkgPath {
		return "", false, nil
	}
	if !redirectMapTypes[obj.Name()] {
		return "", false, nil
	}
	if len(call.Args) != 3 {
		return "", false, fmt.Errorf("%s: %s.Redirect expects (ctx, key, flags)", e.prog.FileSet.Position(call.Pos()), obj.Name())
	}
	// ctx is the program context pointer; it's unused by bpf_redirect_map
	// but we keep it in the Go signature so the call site reads
	// idiomatically alongside other ctx-taking helpers.
	keyExpr, err := e.formatExpr(call.Args[1])
	if err != nil {
		return "", false, err
	}
	flagsExpr, err := e.formatExpr(call.Args[2])
	if err != nil {
		return "", false, err
	}
	return fmt.Sprintf("bpf_redirect_map(&%s, %s, %s)", id.Name, keyExpr, flagsExpr), true, nil
}

// storageMapInfo extracts (mapName, valType, scopeKey) for a TaskStorage /
// SkStorage / InodeStorage method call. scopeKey is the storage Go type
// name ("TaskStorage" etc.) so the caller can look up the right helper.
// Returns ok=false if the call doesn't target a storage map.
func (e *emitter) storageMapInfo(sel *ast.SelectorExpr) (string, types.Type, string, bool) {
	id, ok := sel.X.(*ast.Ident)
	if !ok {
		return "", nil, "", false
	}
	t := e.prog.Info.TypeOf(sel.X)
	if t == nil {
		return "", nil, "", false
	}
	if ptr, isPtr := t.(*types.Pointer); isPtr {
		t = ptr.Elem()
	}
	named, ok := t.(*types.Named)
	if !ok {
		return "", nil, "", false
	}
	obj := named.Obj()
	if obj.Pkg() == nil || obj.Pkg().Path() != bpfPkgPath {
		return "", nil, "", false
	}
	if _, isStorage := storageMapHelpers[obj.Name()]; !isStorage {
		return "", nil, "", false
	}
	targs := named.TypeArgs()
	if targs == nil || targs.Len() != 1 {
		return "", nil, "", false
	}
	return id.Name, targs.At(0), obj.Name(), true
}

// storageMethodCall handles TaskStorage / SkStorage / InodeStorage calls
// that aren't comma-ok Get (those are handled in writeAssignStmt). Covers
// GetOrCreate (returns *V) and Delete (returns int / error in Go terms).
func (e *emitter) storageMethodCall(call *ast.CallExpr) (string, bool, error) {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return "", false, nil
	}
	mapName, _, scope, ok := e.storageMapInfo(sel)
	if !ok {
		return "", false, nil
	}
	helpers := storageMapHelpers[scope]
	pos := e.prog.FileSet.Position(call.Pos())

	switch sel.Sel.Name {
	case "GetOrCreate":
		if len(call.Args) != 2 {
			return "", false, fmt.Errorf("%s: %s.GetOrCreate expects (obj, *V)", pos, scope)
		}
		objExpr, err := e.formatExpr(call.Args[0])
		if err != nil {
			return "", false, err
		}
		valExpr, err := e.formatExpr(call.Args[1])
		if err != nil {
			return "", false, err
		}
		return fmt.Sprintf("%s(&%s, %s, %s, BPF_LOCAL_STORAGE_GET_F_CREATE)", helpers.GetFn, mapName, objExpr, valExpr), true, nil
	case "Delete":
		if len(call.Args) != 1 {
			return "", false, fmt.Errorf("%s: %s.Delete expects (obj)", pos, scope)
		}
		objExpr, err := e.formatExpr(call.Args[0])
		if err != nil {
			return "", false, err
		}
		return fmt.Sprintf("%s(&%s, %s)", helpers.DeleteFn, mapName, objExpr), true, nil
	case "Get":
		// Standalone `taskCtx.Get(task)` (no comma-ok) renders as the raw
		// pointer expression. Comma-ok Get is handled in writeAssignStmt.
		if len(call.Args) != 1 {
			return "", false, fmt.Errorf("%s: %s.Get expects (obj)", pos, scope)
		}
		objExpr, err := e.formatExpr(call.Args[0])
		if err != nil {
			return "", false, err
		}
		return fmt.Sprintf("%s(&%s, %s, NULL, 0)", helpers.GetFn, mapName, objExpr), true, nil
	}
	return "", false, nil
}

// storageGetCall recognizes `<storage>.Get(obj)` for the comma-ok path
// (`v, ok := taskCtx.Get(task)`). Returns (mapName, valType, helperName)
// so the caller can emit the typed declaration with NULL-pointer fallback.
func (e *emitter) storageGetCall(call *ast.CallExpr) (string, types.Type, string, bool) {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return "", nil, "", false
	}
	if sel.Sel.Name != "Get" {
		return "", nil, "", false
	}
	mapName, valType, scope, ok := e.storageMapInfo(sel)
	if !ok {
		return "", nil, "", false
	}
	return mapName, valType, storageMapHelpers[scope].GetFn, true
}

// mapLookupCall returns (mapName, valType, true) if call is `<mapVar>.Lookup(...)`
// where mapVar is a package-level bpf.ArrayMap or bpf.HashMap.
func (e *emitter) mapLookupCall(call *ast.CallExpr) (string, types.Type, bool) {
	mapName, valType, _, ok := e.mapMethodCall(call)
	if !ok {
		return "", nil, false
	}
	sel := call.Fun.(*ast.SelectorExpr)
	if sel.Sel.Name != "Lookup" {
		return "", nil, false
	}
	return mapName, valType, true
}

// mapMethodCall recognizes any `<mapVar>.<Method>(...)` call where mapVar is a
// gobee map type (ArrayMap or HashMap). Returns the map identifier name, its
// value type, the C helper name, and whether the call matches.
func (e *emitter) mapMethodCall(call *ast.CallExpr) (string, types.Type, string, bool) {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return "", nil, "", false
	}
	helper, known := mapMethodToHelper[sel.Sel.Name]
	if !known {
		return "", nil, "", false
	}
	id, ok := sel.X.(*ast.Ident)
	if !ok {
		return "", nil, "", false
	}
	t := e.prog.Info.TypeOf(sel.X)
	if t == nil {
		return "", nil, "", false
	}
	named, ok := t.(*types.Named)
	if !ok {
		return "", nil, "", false
	}
	if !isMapNamed(named) {
		return "", nil, "", false
	}
	targs := named.TypeArgs()
	if targs == nil || targs.Len() != 2 {
		return "", nil, "", false
	}
	return id.Name, targs.At(1), helper, true
}

func isMapNamed(n *types.Named) bool {
	obj := n.Obj()
	if obj.Pkg() == nil || obj.Pkg().Path() != bpfPkgPath {
		return false
	}
	return kernelMapGoTypes[obj.Name()]
}
